"use strict";

const HEADER = `// Generated by Route Atlas. Run it again instead of editing this file by hand.
/* eslint-disable */

type Param = string | number;

function encode(value: Param): string {
  return encodeURIComponent(String(value));
}

function encodeRest(value: Param | readonly Param[]): string {
  return (Array.isArray(value) ? value : String(value).split("/")).map(encode).join("/");
}
`;

function words(text) {
  return text.split(/[^A-Za-z0-9]+/).filter(Boolean);
}

function pascal(text) {
  return words(text)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
}

/** `/users/:id/edit` becomes `usersByIdEdit`, `/` becomes `home`. */
function routeName(routePath) {
  const parts = routePath.split("/").filter(Boolean);
  if (!parts.length) return "home";
  const name = parts.map((part) => (part.startsWith(":") ? `By${pascal(part)}` : pascal(part))).join("");
  if (!name) return "route";
  const camel = name[0].toLowerCase() + name.slice(1);
  return /^\d/.test(camel) ? `_${camel}` : camel;
}

function literal(text) {
  return text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function helper(routePath) {
  const params = [];
  let body = "";
  for (const part of routePath.split("/").filter(Boolean)) {
    const rest = /^:(\w+)\*$/.exec(part);
    const single = /^:(\w+)$/.exec(part);
    if (rest) {
      params.push(`${rest[1]}?: Param | readonly Param[]`);
      body += `\${params.${rest[1]} === undefined ? "" : "/" + encodeRest(params.${rest[1]})}`;
    } else if (single) {
      params.push(`${single[1]}: Param`);
      body += `/\${encode(params.${single[1]})}`;
    } else {
      body += `/${literal(part)}`;
    }
  }
  const unique = [...new Map(params.map((item) => [item.split(/\??:/)[0], item])).values()];
  if (!unique.length) return `() => ${JSON.stringify(routePath)}`;
  const optional = unique.every((item) => item.includes("?:"));
  const fallback = body.startsWith("${") ? ' || "/"' : "";
  return `(params: { ${unique.join("; ")} }${optional ? " = {}" : ""}) => \`${body}\`${fallback}`;
}

/** A TypeScript module with one function per route, so links in the frontend are checked by the compiler. */
function toTypeScript(routes) {
  const used = new Map();
  const entries = [];
  for (const route of [...routes].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))) {
    let name = routeName(route.path);
    const count = used.get(name) || 0;
    used.set(name, count + 1);
    if (count) name += count + 1;
    const methods = route.methods.length ? route.methods.join(", ") : "GET";
    entries.push(`  /** ${methods} ${route.path} (${route.source}) */\n  ${name}: ${helper(route.path)},`);
  }
  const paths = routes.length ? routes.map((route) => JSON.stringify(route.path)).sort().join("\n  | ") : "never";
  return [
    HEADER,
    `export const routes = {\n${entries.join("\n")}\n} as const;`,
    "",
    "export type RouteName = keyof typeof routes;",
    "",
    `export type RoutePath =\n  | ${paths};`,
    "",
    "/** The address of a route: `href(\"usersById\", { id: 42 })`. */",
    "export function href<N extends RouteName>(name: N, ...args: Parameters<(typeof routes)[N]>): string {",
    "  return (routes[name] as (...values: unknown[]) => string)(...args);",
    "}",
    "",
  ].join("\n");
}

module.exports = { toTypeScript, routeName };
